def main():
    dict_dir = os.path.join("crates", "vivivi-modes", "src", "dict")
    os.makedirs(dict_dir, exist_ok=True)
    out_path = os.path.join(dict_dir, "builtin_mit_dict.txt")

    lines = [
        ";; vivivi Built-in Japanese Dictionary (MIT License)",
        ";; Clean, standalone dictionary for punctuation, editor operations, and common words.",
        ";; Freely distributable under the terms of the MIT License.",
    ]

    for yomi in sorted(ENTRIES.keys()):
        cands = ENTRIES[yomi]
        lines.append(f"{yomi} /{'/'.join(cands)}/")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    print(f"Generated {len(ENTRIES)} clean MIT entries to {out_path}")

if __name__ == "__main__":
    main()
